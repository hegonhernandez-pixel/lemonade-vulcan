const IDIOMAS_UI = Object.keys(I18N);
const CLAVE_IDIOMA = "dcrypto.idioma";

/** La preferencia guardada; si no hay, el idioma del navegador; si no lo tenemos, inglés. */
let LANG = (() => {
  try { const g = localStorage.getItem(CLAVE_IDIOMA); if (I18N[g]) return g; } catch { /* sin localStorage */ }
  for (const l of navigator.languages || [navigator.language]) {
    const c = String(l || "").slice(0, 2).toLowerCase();
    if (I18N[c]) return c;
  }
  return "en";
})();

/** T("clave", {param}) en el idioma actual; si falta, en español; si tampoco, la clave. */
function T(clave, p = {}) {
  const s = I18N[LANG]?.[clave] ?? I18N.es[clave] ?? clave;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in p ? p[k] : m));
}
/** Plural: "<clave>.uno" si n es 1, "<clave>.otros" si no. */
function Tn(clave, n, p = {}) { return T(`${clave}.${n === 1 ? "uno" : "otros"}`, { n, ...p }); }

/** Rellena los textos fijos del HTML: data-i18n (texto), data-i18n-html, data-i18n-ph (placeholder),
 *  data-i18n-title (title y aria-label). */
function aplicarI18n(raiz = document) {
  raiz.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = T(el.dataset.i18n); });
  raiz.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = T(el.dataset.i18nHtml); });
  raiz.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = T(el.dataset.i18nPh); });
  raiz.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = T(el.dataset.i18nTitle); el.setAttribute("aria-label", el.title); });
  document.documentElement.lang = LANG;
}

function guardarIdioma(l) {
  if (!I18N[l]) return;
  LANG = l;
  try { localStorage.setItem(CLAVE_IDIOMA, l); } catch { /* sin localStorage: dura hasta recargar */ }
}
